<#
.SYNOPSIS
  Publishes NEXUS LAB site to GitHub Pages and EXEs to GitHub Releases.
#>
param(
  [Parameter(Mandatory = $true)][string]$Repo,
  [string]$Tag = "v2.0.0",
  [string]$Gh = "gh"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$setup = Join-Path $root "release\NEXUS_LAB_Setup.exe"
$portable = Join-Path $root "release\NEXUS_LAB_Portable.exe"
if (-not (Test-Path $setup) -or -not (Test-Path $portable)) {
  throw "Missing release EXEs. Run npm run dist first."
}

$setupSize = (Get-Item $setup).Length
$portableSize = (Get-Item $portable).Length
$owner, $name = $Repo.Split("/")
$pagesUrl = "https://$owner.github.io/$name/"
$releasesUrl = "https://github.com/$Repo/releases/latest"
$setupUrl = "https://github.com/$Repo/releases/download/$Tag/NEXUS_LAB_Setup.exe"
$portableUrl = "https://github.com/$Repo/releases/download/$Tag/NEXUS_LAB_Portable.exe"

$config = @"
/**
 * Public download configuration.
 * Generated by scripts/deploy-public.ps1
 */
window.NEXUS_SITE = {
  version: "2.0.0",
  repo: "$Repo",
  releasesUrl: "$releasesUrl",
  downloads: {
    setup: {
      name: "NEXUS_LAB_Setup.exe",
      url: "$setupUrl",
      sizeBytes: $setupSize,
    },
    portable: {
      name: "NEXUS_LAB_Portable.exe",
      url: "$portableUrl",
      sizeBytes: $portableSize,
    },
  },
};
"@
Set-Content -Path (Join-Path $root "site\js\config.js") -Value $config -Encoding UTF8

# Ensure GitHub repo exists
$exists = & $Gh repo view $Repo 2>$null
if (-not $exists) {
  & $Gh repo create $Repo --public --description "NEXUS LAB — offline Windows sandbox + public download site" --source . --remote github --push
} else {
  $remotes = git remote
  if ($remotes -notcontains "github") {
    git remote add github "https://github.com/$Repo.git"
  }
  git add site scripts website RELEASE.md
  git status --porcelain
  git commit -m "Publish NEXUS LAB public download site" 2>$null
  git push -u github main
}

# Enable GitHub Pages from /site
& $Gh api -X POST "repos/$Repo/pages" -f build_type=legacy -f source='{"branch":"main","path":"/site"}' 2>$null
& $Gh api -X PUT "repos/$Repo/pages" -f build_type=legacy -f source='{"branch":"main","path":"/site"}' 2>$null

# Create or update release with EXEs
$releaseExists = & $Gh release view $Tag --repo $Repo 2>$null
if ($releaseExists) {
  & $Gh release upload $Tag $setup $portable --repo $Repo --clobber
} else {
  & $Gh release create $Tag $setup $portable --repo $Repo --title "NEXUS LAB $Tag" --notes @"
## NEXUS LAB $Tag

Official Windows builds for the offline sandbox application.

### Downloads
- NEXUS_LAB_Setup.exe — installer
- NEXUS_LAB_Portable.exe — portable

Sandbox only. No third-party injection or anti-cheat interference.
"@
}

# Commit config with final URLs and push again
git add site/js/config.js
git commit -m "Point download site at GitHub Release assets" 2>$null
git push github main

Write-Host ""
Write-Host "PUBLIC_SITE=$pagesUrl"
Write-Host "SETUP_URL=$setupUrl"
Write-Host "PORTABLE_URL=$portableUrl"
Write-Host "RELEASES=$releasesUrl"
